"""Generate a distribution's mutation grid as one Bazel target per site (W1883, W1833).

    python3 mutants_gen.py --dist witness [--write | --check]

⚑ THE OPERATOR'S DIRECTION (2026-10-22, real user turns): "flat sharding kills caching", "you want
either exhaustive sharding or targeted sharding", and thousands of targets are fine when the build
files are properly hierarchical. So there is no shard count and no balancing table: each mutation
site is a target, the build files are one package per module under `<dist>/sites/`, and a site
stages exactly what a change to it can move.

⚑ PACKAGES BESIDE `src`, NEVER INSIDE IT: a BUILD file in `src/` makes its directory a package and
drops it from the distribution's own globs. And NOT `<dist>/mutants/`: a target named `mutants`
owns that output path, and the nested package failed to build with a symlink collision (W1885).

⚑ A SITE STAGES ITS MODULE, THE IMPORT CONE OF THE TESTS THAT SEE IT, THOSE TESTS AND THE PACKAGE
`__init__` FILES. The test list is written into the target's own environment (`MUTATE_TESTS`), so
no `graph.json` is staged: the graph changes whenever any file gains an import, and a target that
staged it would rerun for every such change. A module the graph cannot narrow stages the whole
distribution and runs the whole `tests` directory: an unknown is never read as "nothing else
matters".

⚑ A DEF-SITE TARGET OMITS `mutants.regex`, so editing a declaration reruns no def-site; a declared
defect's target stages it (the runner reads its line from there) and so reruns when any declaration
changes, which is accepted.

⚑ NAMES ARE THE SITE'S OWN, never an index: inserting a function renames nothing else, and a
renamed target leaves dead metric series for one retention window (luthen-observability:W1568).

⚑ GENERATED FILES ARE CHECKED, NOT TRUSTED: `--check` exits 1 naming every file that differs from
what would be written, including a package whose module is gone.
"""

import argparse
import dataclasses
import pathlib
import re
import sys
from typing import cast

import mutate_runner

SITES = "sites"
BUILD = "BUILD.bazel"
HEADER = (
    "# GENERATED by check_mutants/mutants_gen.py - do not edit: the whole file is rewritten.\n"
    "# REGENERATE: python3 check_mutants/mutants_gen.py --dist {dist} --write\n"
)
LOAD = 'load("@mikemol_check_mutants//:defs.bzl", "mutant_site")\n'
EXIT_STALE = 1
EXIT_USAGE = 2
_UNSAFE = re.compile(r"[^A-Za-z0-9_.-]")


@dataclasses.dataclass(frozen=True)
class Cell:
    """One mutation cell: a def-site or a declared defect, and what it stages."""

    key: str
    module: str
    sources: tuple[str, ...]
    tests: tuple[str, ...]
    declared: bool = False

    @property
    def name(self) -> str:
        """Name the target after the cell's own part of its key.

        Returns:
            the part after `::`, made safe for a target name, and prefixed for a declared defect
            so it cannot collide with a function of the same name.

        """
        own = _UNSAFE.sub("_", self.key.partition("::")[2])
        return f"declared_{own}" if self.declared else own


def package_of(dist: str, module: str) -> str:
    """Name the package that holds a module's sites.

    Returns:
        `<dist>/sites/<module path without .py>`.

    """
    return f"{dist}/{SITES}/{module.removesuffix('.py')}"


def label(dist: str, path: str) -> str:
    """Spell a dist-relative file as a label the generated packages may use.

    Returns:
        `//<dist>:<path>`.

    """
    return f"//{dist}:{path}"


def _paths(dist_dir: pathlib.Path, folder: str, pattern: str) -> list[str]:
    # Dist-relative paths of the files under one folder, sorted.
    return sorted(str(p.relative_to(dist_dir)) for p in (dist_dir / folder).rglob(pattern))


def _staged(dist_dir: pathlib.Path, module: str) -> tuple[tuple[str, ...], tuple[str, ...]]:
    # The sources and tests a module's cells stage: the cone, or everything when it is unknown.
    narrowed = mutate_runner.staged_files(dist_dir, pathlib.Path(module))
    if narrowed is None:
        return tuple(_paths(dist_dir, "src", "*.py")), ()
    inits = _paths(dist_dir, "src", "__init__.py")
    return tuple(sorted({*narrowed[0], *inits})), tuple(narrowed[1])


def cells_of(dist_dir: pathlib.Path) -> list[Cell]:
    """List every cell of a distribution with the files it stages.

    Returns:
        the def-sites in source order, then the declared defects in file order.

    """
    found: list[Cell] = []
    for key in mutate_runner.site_keys(dist_dir):
        module = key.partition("::")[0]
        sources, tests = _staged(dist_dir, module)
        found.append(Cell(key, module, sources, tests))
    for declared in mutate_runner.read_declared(dist_dir):
        sources, tests = _staged(dist_dir, declared.module)
        found.append(Cell(declared.label, declared.module, sources, tests, declared=True))
    return found


def _list(items: list[str]) -> str:
    return "".join(f'        "{item}",\n' for item in items)


def render_module(dist: str, cells: list[Cell], everything_tests: list[str]) -> str:
    """Write one module package's BUILD file.

    Returns:
        the file's text: a `mutant_site` per cell and a `suite` over them.

    """
    out = HEADER.format(dist=dist) + "\n" + LOAD
    for cell in cells:
        files = list(cell.sources) + (list(cell.tests) or everything_tests)
        data = [label(dist, path) for path in files]
        if cell.declared:
            data.append(label(dist, "mutants.regex"))
        out += (
            "\nmutant_site(\n"
            f'    name = "{cell.name}",\n'
            f'    dist = "{dist}",\n'
            f'    site = "{cell.key}",\n'
            f'    tests = "{" ".join(cell.tests)}",\n'
            "    data = [\n" + _list(data) + "    ],\n)\n"
        )
    names = "".join(f'        ":{cell.name}",\n' for cell in cells)
    return (
        out
        + '\ntest_suite(\n    name = "suite",\n    tests = [\n'
        + names
        + f'    ],\n    tags = ["manual"],\n    visibility = ["//{dist}/{SITES}:__pkg__"],\n)\n'
    )


def render_root(dist: str, modules: list[str]) -> str:
    """Write the distribution's `sites` BUILD file.

    Returns:
        the file's text: one `suite` over every module's suite.

    """
    inner = "".join(f'        "//{package_of(dist, m)}:suite",\n' for m in modules)
    return (
        HEADER.format(dist=dist)
        + '\ntest_suite(\n    name = "suite",\n    tests = [\n'
        + inner
        + '    ],\n    tags = ["manual"],\n    visibility = ["//visibility:public"],\n)\n'
    )


def generate(dist_dir: pathlib.Path) -> dict[str, str]:
    """Render every generated file of a distribution.

    Returns:
        repo-relative path -> text: the root file and one package per module that has a cell.

    """
    dist = dist_dir.name
    everything_tests = _paths(dist_dir, "tests", "*.py")
    by_module: dict[str, list[Cell]] = {}
    for cell in cells_of(dist_dir):
        by_module.setdefault(cell.module, []).append(cell)
    files = {
        f"{package_of(dist, module)}/{BUILD}": render_module(dist, group, everything_tests)
        for module, group in by_module.items()
    }
    files[f"{dist}/{SITES}/{BUILD}"] = render_root(dist, sorted(by_module))
    return files


def _read(path: pathlib.Path) -> str | None:
    # A file's text, or None when it does not exist.
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return None


def stale(root: pathlib.Path, dist: str, files: dict[str, str]) -> list[str]:
    """Name every generated file that differs from what would be written.

    Returns:
        the repo-relative paths: changed or missing ones, and ones whose module is gone.

    """
    changed = [rel for rel, text in files.items() if _read(root / rel) != text]
    folder = root / dist / SITES
    present = {str(p.relative_to(root)) for p in folder.rglob(BUILD)} if folder.is_dir() else set()
    return sorted(changed + sorted(present - set(files)))


def main(argv: list[str]) -> int:
    """Generate, check or write a distribution's per-site packages.

    Returns:
        0 when written or fresh, EXIT_STALE when `--check` finds a difference, EXIT_USAGE for a
        distribution with no `src`.

    """
    parser = argparse.ArgumentParser(prog="mutants_gen")
    parser.add_argument("--dist", required=True, help="the distribution's directory under the root")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    root = pathlib.Path.cwd()
    dist_dir = root / cast("str", args.dist)
    write, check = cast("bool", args.write), cast("bool", args.check)
    if not (dist_dir / "src").is_dir():
        sys.stderr.write(f"mutants_gen: {dist_dir}/src is not a directory\n")
        return EXIT_USAGE
    files = generate(dist_dir)
    if write:
        for rel, text in files.items():
            (root / rel).parent.mkdir(parents=True, exist_ok=True)
            (root / rel).write_text(text, encoding="utf-8")
        sys.stdout.write(f"mutants_gen: wrote {len(files)} file(s) for {dist_dir.name}\n")
        return 0
    differing = stale(root, dist_dir.name, files)
    sys.stdout.write("".join(f"mutants_gen: stale {rel}\n" for rel in differing))
    return EXIT_STALE if check and differing else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
